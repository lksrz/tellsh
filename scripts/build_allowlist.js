#!/usr/bin/env node
// Builds src/allowlist-data.js: the commands, subcommands and flags the catalog renders for every shell (the allowlist
// of the danger checker, src/danger.js). Slot values are marked (`zq…`) so a value is never taken for a subcommand.
// Run after changing a template: node scripts/build_allowlist.js (test/allowlist.test.js fails when it is stale).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { allowlistTable } from './lib/allowlist_table.js';

const out = fileURLToPath(new URL('../src/allowlist-data.js', import.meta.url));
const table = allowlistTable();
const lines = Object.keys(table).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(table[k])},`);
writeFileSync(out, `// GENERATED by scripts/build_allowlist.js from the catalog templates (all shells). Do not edit by hand.
// command key (program + known subcommand words) -> the flags tellsh renders for it ('*sub': any operand after the key)
export const ALLOW = {
${lines.join('\n')}
};
`);
console.log(`allowlist: ${Object.keys(table).length} command keys -> ${out}`);
